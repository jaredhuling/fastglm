percent <- function(x) sprintf("%.2f%%",100*x)
entry <- function(g) paste0(percent(g$rate)," (",percent(g$lower)," to ",percent(g$upper),")")
table <- function(null,test) {
    z <- rates[rates$null==null & rates$level==.05 & rates$test==test,]
    vapply(sort(unique(z$cell)),function(i) {
        g <- z[z$cell==i,]; ml <- g[g$estimation=="ML",]; br <- g[g$estimation=="meanBR",]
        paste0("| ",ml$scenario," | ",ml$n," | ",ml$available," / ",br$available,
            " | ",entry(ml)," | ",entry(br)," |")
    },character(1))
}
