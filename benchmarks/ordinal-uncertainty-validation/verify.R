# Validate saved evidence and regenerate summaries without fitting models.
args<-commandArgs(TRUE)
directory<-if(length(args))args[1L] else "benchmarks/ordinal-uncertainty-validation/development-v1"
text<-readLines(file.path(directory,"runner.R"))
cut<-which(startsWith(text,"if(stage %in% c(\"summarize\",\"audit\"))"))[1L]
stopifnot(is.finite(cut))
e<-new.env(parent=globalenv())
eval(parse(text=paste(text[seq_len(cut-1L)],collapse="\n")),e)
meta<-readRDS(file.path(directory,"manifest.rds"))
payload<-e$records(directory)
e$audit(directory)
for(z in payload) {
    s<-e$scenarios[e$scenarios$scenario==z$scenario,,drop=FALSE]
    regenerated<-e$generate(s,z$data.seed)
    stopifnot(identical(regenerated$hash,z$data.hash),identical(regenerated$category.counts,z$category.counts),
              identical(e$truth(s),z$truth))
    for(f in z$fits) if(!is.null(f$bootstrap) && isTRUE(f$bootstrap$inference.available)) {
        b<-f$bootstrap
        ci<-t(apply(b$replicates,2L,quantile,probs=c((1-b$level)/2,(1+b$level)/2),names=FALSE))
        stopifnot(isTRUE(all.equal(unname(ci),unname(b$conf.int),tolerance=1e-14)),
                  isTRUE(all.equal(apply(b$replicates,2L,sd),b$std.error,tolerance=1e-14)))
    }
}
files<-file.path(directory,c("interval-records.csv","fit-records.csv","summary.csv","point-summary.csv",
                            "paired-differences.csv","paired-estimators.csv","simultaneous-diagnostics.csv"))
old<-tools::md5sum(files)
e$summarize(directory)
stopifnot(identical(old,tools::md5sum(files)))
installed<-meta$identity$installed
installed.check<-if(all(file.exists(installed$path))) {
    stopifnot(identical(as.character(tools::md5sum(installed$path)),installed$md5));"Historical installed-method hashes unchanged."
} else "Historical local installation absent; binary identity is retained in installed-hashes.csv."
writeLines(c(paste("Regenerated datasets and data hashes:",length(payload)),
             "Truth, category frequencies, percentile endpoints, and bootstrap standard errors verified.",
             "Derived CSV summaries regenerated byte-for-byte from stored records.",installed.check),
           file.path(directory,"verification.txt"))
