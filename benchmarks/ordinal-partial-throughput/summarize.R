profile.path <- "benchmarks/ordinal-partial-throughput/profile-20261104"
baseline.path <- "benchmarks/ordinal-partial-throughput/comparison-baseline-20261104"
current.path <- "benchmarks/ordinal-partial-throughput/comparison-current-20261104"
baseline <- readRDS(file.path(baseline.path,"records.rds"))
current <- readRDS(file.path(current.path,"records.rds"))
stopifnot(length(baseline)==length(current))
keys <- c("n","K","r","link","firth","representation")
checks <- comparisons <- vector("list",length(current))
for(i in seq_along(current)) {
    a <- baseline[[i]];b <- current[[i]]
    stopifnot(identical(a[keys],b[keys]))
    same <- vapply(c("coefficients","covariance","history","iterations","evaluations",
        "fallbacks","scaled.score","predictor.step","minimum.gap","loglik","equations"),
        function(key) identical(a[[key]],b[[key]]),logical(1))
    passes <- if(b$representation=="source") a$source.passes-b$source.passes else NA_integer_
    checks[[i]] <- data.frame(a[keys],converged=isTRUE(a$converged)&&isTRUE(b$converged),
        identical.values=all(same),passes.saved=passes,
        expected.saved=if(b$representation=="source") b$iterations-1L else NA_integer_)
    comparisons[[i]] <- data.frame(a[keys],d=b$d,baseline.ms=1000*a$median,
        current.ms=1000*b$median,ratio=b$median/a$median,
        baseline.passes=if(b$representation=="source") a$source.passes else NA_integer_,
        current.passes=if(b$representation=="source") b$source.passes else NA_integer_)
}
checks <- do.call(rbind,checks);comparisons <- do.call(rbind,comparisons)
write.csv(checks,file.path(current.path,"checks.csv"),row.names=FALSE)
write.csv(comparisons,file.path(current.path,"comparisons.csv"),row.names=FALSE)
stopifnot(all(checks$converged),all(checks$identical.values),
    all(checks$passes.saved==checks$expected.saved,na.rm=TRUE))
components <- read.csv(file.path(profile.path,"components.csv"))
components$total <- rowSums(components[c("information","factorization","adjustment","score_update","predictor_scan")])
components$factor.percent <- 100*components$factorization/components$total
profile.records <- readRDS(file.path(profile.path,"records.rds"))
maximum.error <- max(vapply(profile.records,function(z) max(z$normalized),numeric(1)))
report <- character()
add <- function(...) report <<- c(report,unlist(list(...),use.names=FALSE))
fmt <- function(x) format(signif(x,4),trim=TRUE,scientific=FALSE)
table <- function(x) {
    old <- options(width=180);on.exit(options(old))
    report <<- c(report,capture.output(print(x,row.names=FALSE,digits=4)))
}
