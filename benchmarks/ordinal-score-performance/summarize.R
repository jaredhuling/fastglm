args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)<=1L)
destination <- if(length(args)) args[1L] else "benchmarks/ordinal-score-performance/confirmation"
read <- function(implementation,name) read.csv(file.path(destination,paste0(implementation,"-",name,".csv")))
a <- read("baseline","inputs"); b <- read("candidate","inputs")
stopifnot(identical(a[c("case","n","p","K","estimation","input.hash")],
    b[c("case","n","p","K","estimation","input.hash")]),nrow(a)==8L,
    identical(a$case,rep(1:4,each=2)),all(a$converged),all(b$converged))
coefficient <- merge(read("baseline","coefficients"),read("candidate","coefficients"),
    by=c("case","estimation","coefficient"),suffixes=c(".baseline",".candidate"))
stopifnot(all(abs(coefficient$estimate.candidate-coefficient$estimate.baseline)<=
    1e-8*pmax(1,abs(coefficient$estimate.baseline))))
write.csv(coefficient,file.path(destination,"coefficient-equivalence.csv"),row.names=FALSE)
a <- read("baseline","results"); b <- read("candidate","results")
key <- c("case","estimation","operation","repetition","hypothesis")
z <- merge(a,b,by=key,suffixes=c(".baseline",".candidate"))
stopifnot(nrow(z)==nrow(a),nrow(z)==nrow(b),nrow(z)==360L,
    identical(z$available.baseline,z$available.candidate),all(z$available.baseline),
    identical(z$df.baseline,z$df.candidate),identical(z$reason.baseline,z$reason.candidate))
z$statistic.relative.error <- abs(z$statistic.candidate-z$statistic.baseline)/pmax(1,abs(z$statistic.baseline))
z$p.value.absolute.error <- abs(z$p.value.candidate-z$p.value.baseline)
stopifnot(all(z$statistic.relative.error<=1e-8),all(z$p.value.absolute.error<=1e-8))
write.csv(z,file.path(destination,"equivalence.csv"),row.names=FALSE)
timing <- rbind(read("baseline","timing"),read("candidate","timing"))
stopifnot(nrow(timing)==240L)
medians <- aggregate(seconds~implementation+case+n+p+K+estimation+operation,timing,median)
comparison <- merge(subset(medians,implementation=="baseline",select=-implementation),
    subset(medians,implementation=="candidate",select=-implementation),
    by=c("case","n","p","K","estimation","operation"),suffixes=c(".baseline",".candidate"))
comparison$speedup <- comparison$seconds.baseline/comparison$seconds.candidate
write.csv(comparison,file.path(destination,"timing-summary.csv"),row.names=FALSE)
allocation <- merge(read("baseline","allocations"),read("candidate","allocations"),
    by=c("case","estimation"),suffixes=c(".baseline",".candidate"))
write.csv(allocation,file.path(destination,"allocation-summary.csv"),row.names=FALSE)
print(comparison,row.names=FALSE)
print(allocation,row.names=FALSE)
cat("Maximum relative statistic error:",max(z$statistic.relative.error),"\n")
table <- c("| Rows | Predictors | Categories | Null | Operation | Baseline (ms) | Candidate (ms) | Speedup |",
    "|---:|---:|---:|:---|:---|---:|---:|---:|")
labels <- c(kernel="Score calculation",joint="Complete joint test",terms="Joint and all terms")
for(j in seq_len(nrow(comparison))) {
    r <- comparison[j,]
    table <- c(table,sprintf("| %s | %d | %d | %s | %s | %.1f | %.1f | %.2fx |",
        format(r$n,big.mark=",",scientific=FALSE,trim=TRUE),r$p,r$K,r$estimation,
        labels[r$operation],1000*r$seconds.baseline,1000*r$seconds.candidate,r$speedup))
}
allocation.table <- c("| Null | Baseline allocated (MiB) | Candidate allocated (MiB) | Reduction |",
    "|:---|---:|---:|---:|")
for(j in seq_len(nrow(allocation))) {
    r <- allocation[j,]
    allocation.table <- c(allocation.table,sprintf("| %s | %.1f | %.1f | %.1f%% |",r$estimation,
        r$allocated.bytes.baseline/2^20,r$allocated.bytes.candidate/2^20,
        100*(1-r$allocated.bytes.candidate/r$allocated.bytes.baseline)))
}
writeLines(c("# Ordinal score-test performance assessment","",
    "Generated by `summarize.R` from the retained confirmation records. See",
    "`PROTOCOL.md` for the frozen design, source reconstruction, and rerun commands.","",
    "All eight data/null combinations converged. Input hashes matched, and all",
    "360 paired test records agreed on availability and degrees of freedom.",
    sprintf("The maximum relative statistic difference was %.3g, below the prespecified 1e-8 tolerance.",max(z$statistic.relative.error)),
    sprintf("The largest absolute p-value difference was %.3g.",max(z$p.value.absolute.error)),"",
    "## Median elapsed times","",
    "Each median uses five repetitions after an untimed warm-up. The complete",
    "joint test includes its null refit. The final operation compares independent",
    "joint/per-term calls with a shared null fit and information calculation.","",table,"",
    "## Allocations","",
    "R-managed cumulative allocations for the score calculation with 30,000 rows,",
    "12 predictors and 8 categories. These totals are not peak resident memory",
    "and exclude untracked native allocations.","",allocation.table,"",
    "## Interpretation and limits","",
    "The largest arithmetic savings occur as predictor and category counts grow.",
    "Complete-test speedups also depend on the null-fitting cost. Sharing that",
    "fit makes joint-plus-term analysis substantially cheaper than separate calls.",
    "The comparison preserves the score statistic and does not add a small-sample",
    "correction, change the null estimator, or establish finite-sample calibration.","",
    "These are single-machine logit benchmarks. No timing claim is made for probit",
    "or complementary-log-log models, other hardware, or ordinal estimation itself.",
    "The two implementations were run sequentially, so time-order effects are not",
    "removed by randomization. Raw repetitions and environment records are retained.","",
    "## Correctness checks beyond the timing comparison","",
    "The package tests compare new-link likelihood fits with `MASS::polr`, binary",
    "bias-reduced fits with the corresponding GLMs, and scores, information, bias",
    "adjustments, common-slope statistics, and marginal-effect standard errors",
    "with independent numerical derivatives. Grouped/expanded data, offsets,",
    "robust covariance, prepared designs, refits, and extreme-tail calculations",
    "are exercised separately. Wald tests are checked against analytic quadratic",
    "forms, Gaussian nested-model statistics, single-coefficient GLM tests,",
    "estimability constraints, covariance reordering, and coordinate rescaling."),
    if(length(args)) file.path(destination,"ASSESSMENT.md") else "benchmarks/ordinal-score-performance/ASSESSMENT.md")
