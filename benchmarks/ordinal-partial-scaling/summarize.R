args <- commandArgs(trailingOnly=TRUE)
if(length(args)!=2L) stop("Supply a results directory and report filename")
root <- normalizePath(args[1L]);report <- args[2L]
records <- read.csv(file.path(root,"records.csv"))
baseline <- readRDS(file.path(root,"baseline.rds"))
current <- readRDS(file.path(root,"current.rds"))
profile <- readRDS(file.path(root,"profile.rds"))
configuration <- readRDS(file.path(root,"configuration.rds"))
environment <- readRDS(file.path(root,"environment.rds"))
stopifnot(nrow(records)==54L,!anyDuplicated(records[c("K","r","link","firth")]))
successful <- records[records$status=="ok",]
stopifnot(all(successful$d==(successful$K-1L)+configuration$common+(successful$K-1L)*successful$r))
comparisons <- do.call(rbind,lapply(seq_along(baseline$records),function(i) {
    b <- baseline$records[[i]];a <- current$records[[i]]
    stopifnot(identical(b[c("model","link","firth")],a[c("model","link","firth")]))
    fields <- c("loglik","score","ordinary.score","adjustment","information","cov.unscaled","step")
    difference <- max(vapply(fields,function(key) max(abs(a$evaluation[[key]]-b$evaluation[[key]])),numeric(1)))
    data.frame(model=a$model,link=a$link,firth=a$firth,
        baseline.native.ms=1e3*b$evaluate$seconds,current.native.ms=1e3*a$evaluate$seconds,
        native.ratio=a$evaluate$seconds/b$evaluate$seconds,
        baseline.fit.ms=1e3*b$fit$seconds,current.fit.ms=1e3*a$fit$seconds,
        fit.ratio=a$fit$seconds/b$fit$seconds,
        coefficient.difference=max(abs(a$coefficients-b$coefficients)),
        covariance.difference=max(abs(a$covariance-b$covariance)),equation.difference=difference)
}))
write.csv(comparisons,file.path(root,"baseline-comparison.csv"),row.names=FALSE)
paired <- merge(successful[!successful$firth,c("K","r","link","native.seconds")],
    successful[successful$firth,c("K","r","link","native.seconds")],
    by=c("K","r","link"),suffixes=c(".ML",".BR"))
paired$BR.to.ML <- paired$native.seconds.BR/paired$native.seconds.ML
paired$additional.seconds <- paired$native.seconds.BR-paired$native.seconds.ML
write.csv(paired,file.path(root,"adjustment-comparison.csv"),row.names=FALSE)
corners <- successful[!is.na(successful$stream.seconds),]
largest <- successful[successful$d==max(successful$d),
    c("K","r","d","link","firth","native.seconds","dense.seconds","prepared.seconds","stream.seconds","iterations","source.passes")]
largest[,grep("seconds$",names(largest))] <- largest[,grep("seconds$",names(largest))]*1000
names(largest) <- sub("seconds$","ms",names(largest))
fmt <- function(x,digits=3L) format(signif(x,digits),trim=TRUE,scientific=FALSE)
limits <- function(x) paste(fmt(range(x,na.rm=TRUE)),collapse=" to ")
native.share <- if('".Call"'%in%rownames(profile$by.total)) profile$by.total['".Call"',"total.pct"] else NA_real_
text <- capture.output({
    cat("Partial ordinal computational scaling: development report\n")
    cat("=========================================================\n\n")
    cat("Generated by benchmarks/ordinal-partial-scaling/summarize.R from\n")
    cat(args[1L],"\n\n",sep="")
    cat("Scope and provenance\n--------------------\n")
    cat("This is a fixed-design computational development study, not a coverage\n")
    cat("study or evidence that every partial-model adjusted-score root is interior.\n")
    cat("The grid uses",configuration$n,"rows,",configuration$common,"common predictors,\n")
    cat("K in {3,5,9}, and r in {1,4,8} varying predictors under all three links\n")
    cat("and ML/meanBR. Actual parameter dimensions range from",min(successful$d),"to",max(successful$d),".\n")
    cat("In particular, K=9 and r=8 give d=8+2+8*8=74. Counts are positive\n")
    cat("at every row/category; these cases examine dimension growth away from\n")
    cat("ordering boundaries. All runs used one OpenMP/OpenBLAS/vecLib thread.\n")
    cat("Package version:",environment$version,"; platform:",environment$session$platform,".\n")
    cat("Current library:",current$library,"\n")
    cat("Supplied baseline 351d808 library:",baseline$library,"\n")
    cat("Exact source hashes, installed binary hashes, settings, sessions, and\n")
    cat("per-cell records are retained in the results directory.\n\n")
    cat("Correctness and retained storage\n--------------------------------\n")
    cat(nrow(successful),"of",nrow(records),"cells converged;",sum(records$status!="ok"),"failed.\n")
    cat("Maximum scaled score:",format(max(successful$scaled.score),digits=5),".\n")
    cat("Optimizer iterations:",limits(successful$iterations),"; fallbacks:",limits(successful$fallbacks),".\n")
    cat(nrow(corners),"dense/prepared/source corner comparisons passed.\n")
    cat("Maximum coefficient difference:",format(max(corners$coefficient.difference),digits=5),".\n")
    cat("Maximum covariance difference:",format(max(corners$covariance.difference),digits=5),".\n")
    cat("All source fits omitted retained x/y fields and read blocks of at most",
        max(corners$maximum.block.rows),"rows.\n")
    cat("The native source stores one block and parameter-sized matrices; no\n")
    cat("expanded observation-by-threshold-by-parameter design is formed.\n")
    cat("This reader deliberately closes over the dense comparison fixture, so\n")
    cat("these results do not establish end-to-end external-storage peak memory.\n\n")
    cat("Profiling and scaling\n---------------------\n")
    cat("The initial R profile sampled only",fmt(profile$sampling.time*1000),"ms;",
        fmt(native.share),"% was in native calls.\n")
    cat("This is coarse localization, not enough samples to attribute cost to\n")
    cat("individual C++ operations or justify a factorization rewrite.\n")
    cat("Dense whole-fit times ranged from",limits(1000*successful$dense.seconds),"ms.\n")
    cat("Native evaluation times ranged from",limits(1000*successful$native.seconds),"ms.\n")
    cat("MeanBR/ML native evaluation time ratios ranged from",limits(paired$BR.to.ML),
        "; median",fmt(median(paired$BR.to.ML)),".\n")
    cat("These paired differences estimate adjustment overhead but do not\n")
    cat("separate likelihood accumulation, information factorization, and all\n")
    cat("other native work. The largest models were:\n\n")
    print(largest,row.names=FALSE,digits=4)
    cat("\nPrepared/dense whole-fit ratios at the corners ranged from",
        limits(corners$prepared.seconds/corners$dense.seconds),".\n")
    cat("At this small row count, setup reuse brings modest and noisy timing gains.\n")
    cat("Stream/dense ratios ranged from",limits(corners$stream.seconds/corners$dense.seconds),
        "; source passes ranged from",limits(corners$source.passes),".\n")
    cat("Streaming therefore pays measurable reader/pass overhead in exchange\n")
    cat("for its storage contract. It is not a speed advantage on these dense\n")
    cat("fixtures. Direction bounds and row-domain checks require source passes\n")
    cat("in addition to global information and bias-adjustment evaluations.\n\n")
    cat("Baseline regression check\n-------------------------\n")
    cat("All",nrow(comparisons),"common/partial model comparisons retained identical\n")
    cat("coefficients, covariance, and native equations; maximum differences:\n")
    cat("coefficients",max(comparisons$coefficient.difference),"; covariance",
        max(comparisons$covariance.difference),"; equations",max(comparisons$equation.difference),".\n")
    cat("Ratios below are current/baseline elapsed time, so values above one\n")
    cat("mean longer measured time.\n\n")
    print(comparisons[,c("model","link","firth","baseline.native.ms","current.native.ms",
        "native.ratio","baseline.fit.ms","current.fit.ms","fit.ratio")],row.names=FALSE,digits=4)
    cat("\nPartial whole-fit ratios:",limits(comparisons$fit.ratio[comparisons$model=="partial"]),".\n")
    cat("Common whole-fit ratios:",limits(comparisons$fit.ratio[comparisons$model=="common"]),".\n")
    cat("The 0.05/0.10 ms common-logit evaluation comparison is too close to\n")
    cat("timer granularity to interpret its twofold ratio as a regression. The\n")
    cat("whole-fit comparisons show no material slowdown in these small cases.\n")
    cat("Five repetitions, fixed process order, and timer resolution limit the\n")
    cat("precision; differences of a few percent should not be treated as gains.\n\n")
    cat("Decision and remaining limits\n-----------------------------\n")
    cat("Keep the current dense factorization. Dimensions through 74 parameters\n")
    cat("are fast in this bounded study, and the profile cannot identify a solver\n")
    cat("bottleneck. A useful next development experiment would profile larger\n")
    cat("dimensions at native-operation granularity and separately measure source\n")
    cat("callback/pass costs before changing the implementation.\n")
    cat("Sparse individual-outcome data can still approach an ordering boundary\n")
    cat("without a converged meanBR root. The retained coded-response regression\n")
    cat("has the same explicit failures under baseline and current native code;\n")
    cat("it remains outside the successful timing grid and does not receive\n")
    cat("covariance-based inference. No convergence criterion or estimator was\n")
    cat("changed to improve these results.\n")
})
writeLines(text,report)
files <- list.files(dirname(root),recursive=TRUE,full.names=TRUE)
manifest <- file.path(root,"artifacts.csv")
files <- files[files!=manifest]
write.csv(data.frame(file=substring(files,nchar(dirname(root))+2L),
    bytes=file.info(files)$size,md5=unname(tools::md5sum(files))),manifest,row.names=FALSE)
cat(paste(text,collapse="\n"),"\n")
