test_that("public ordinal diagnostics request row details explicitly", {
    x <- cbind(z=seq(-1,1,length.out=12))
    counts <- cbind(low=rep(4,12),middle=rep(c(2,3),6),high=rep(c(3,2,4),4))
    source <- fastglm_source(function(k) {
        at <- seq.int((k-1L)*4L+1L,k*4L)
        list(X=x[at,,drop=FALSE],y=counts[at,,drop=FALSE])
    },3L)
    fit <- fastglm_ordinal_streaming(source,nonparallel="z",firth=TRUE)
    before <- fit$state$passes
    stored <- fastglm_diagnostics(fit)
    expect_identical(fit$state$passes,before)
    expect_null(stored$boundary.details)
    expect_equal(stored$raw.score.maximum,max(abs(fit$effective$score)))
    details <- fastglm_diagnostics(fit,boundary=TRUE,max.rows=2L)
    expect_identical(fit$state$passes,before+1L)
    expect_true(details$boundary.details$available)
    expect_lte(nrow(details$boundary.details$smallest.probabilities),2L)
    expect_output(print(details),"Observed frequency")
    expect_output(print(details),"Additional source passes")
    expect_equal(as.data.frame(details)$boundary.details[[1L]],details$boundary.details)
    expect_error(fastglm_diagnostics(fit,boundary=NA),"TRUE or FALSE")
    expect_error(fastglm_diagnostics(fit,boundary=TRUE,max.rows=0),"positive integer")
    fit$fetch <- NULL
    unavailable <- fastglm_diagnostics(fit,boundary=TRUE)
    expect_false(unavailable$boundary.details$available)
    expect_output(print(unavailable),"recorded block reader")
    glm <- fastglm(cbind(1,1:8),1:8,gaussian())
    expect_error(fastglm_diagnostics(glm,boundary=TRUE),"ordinal fit")
})
