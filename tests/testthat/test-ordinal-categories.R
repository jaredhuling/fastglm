test_that("ordinal category mapping preserves declared endpoints and unused interior levels", {
    y<-ordered(c("low","high","low","unused"),levels=c("low","unused","high"))
    a<-fastglm:::.ordinal_response_data(y,c(2,3,1,0),firth=TRUE)
    expect_identical(a$levels,c("low","high"))
    expect_identical(a$original.levels,levels(y))
    expect_identical(a$retained.categories,c(1L,3L))
    expect_identical(a$threshold.map,c(1L,1L))
    expect_identical(a$codes,c(1L,2L,1L,1L))
    expect_identical(a$original.codes,c(1L,3L,1L,2L))
    expect_equal(a$category.totals,c(3,3))
    expect_equal(a$totals,c(2,3,1,0))
    expect_true(a$boundary)
    expect_identical(a$empty.end.categories,integer())
    ml<-fastglm:::.ordinal_response_data(y,c(2,3,1,0),firth=FALSE)
    expect_identical(ml$threshold.map,a$threshold.map)
})

test_that("consecutive empty categories keep only the original outer endpoints for bias reduction", {
    y<-rbind(c(0,0,2,3,0,0),c(0,0,4,1,0,0))
    colnames(y)<-letters[1:6]
    a<-fastglm:::.ordinal_response_data(y,c(2,1),firth=TRUE)
    expect_identical(a$retained.categories,c(1L,3L,4L,6L))
    expect_identical(a$collapsed.categories,c(2L,5L))
    expect_identical(a$empty.end.categories,c(1L,6L))
    expect_identical(a$threshold.map,c(1L,1L,2L,3L,3L))
    expect_equal(a$category.totals,c(0,8,7,0))
    expect_equal(a$totals,c(10,5))
    expect_equal(a$counts,y[,a$retained.categories,drop=FALSE])
    expect_error(fastglm:::.ordinal_response_data(y,c(2,1)),"infinite thresholds for empty endpoint")
    rev<-fastglm:::.ordinal_response_data(y[,6:1],c(2,1),firth=TRUE)
    expect_identical(rev$threshold.map,length(a$levels)-rev(a$threshold.map))
    expect_equal(rev$category.totals,rev(a$category.totals))
})

test_that("frequency mapping is identical for grouped counts and repeated observations", {
    counts<-rbind(c(3,0,2),c(1,0,4));weights<-c(2,3)
    grouped<-fastglm:::.ordinal_response_data(counts,weights,firth=TRUE)
    y<-ordered(rep(1:3,colSums(counts*weights)),levels=1:3)
    individual<-fastglm:::.ordinal_response_data(y,firth=TRUE)
    expect_identical(grouped$category.totals,individual$category.totals)
    expect_identical(grouped$retained.categories,individual$retained.categories)
    expect_identical(grouped$threshold.map,individual$threshold.map)
    scaled<-fastglm:::.ordinal_response_data(counts,10*weights,firth=TRUE)
    expect_equal(scaled$category.totals,10*grouped$category.totals)
    expect_identical(scaled$weights,as.numeric(10*weights))
    expect_error(fastglm:::.ordinal_response_data(counts,c(.3,1),firth=TRUE),"integer effective")
    effective<-fastglm:::.ordinal_response_data(2*counts,c(.5,1.5),firth=TRUE)
    expect_equal(effective$category.totals,colSums(counts*c(1,3))[c(1,3)])
})

test_that("declared scale is distinct from the observed category count", {
    a<-fastglm:::.ordinal_response_data(ordered(rep("middle",5),levels=c("low","middle","high")),firth=TRUE)
    expect_identical(a$levels,c("low","middle","high"))
    expect_equal(a$category.totals,c(0,5,0))
    expect_false(a$boundary)
    expect_error(fastglm:::.ordinal_response_data(ordered(rep("middle",5)),firth=TRUE),"two distinct")
    b<-fastglm:::.ordinal_response_data(c(1L,3L,1L),levels=c("low","unused","high"),firth=TRUE)
    expect_identical(b$codes,c(1L,2L,1L))
    expect_error(fastglm:::.ordinal_response_data(c(0L,1L),levels=c("low","high"),firth=TRUE),"category codes")
    expect_error(fastglm:::.ordinal_response_data(matrix(1,2,2),levels=c("a","a"),firth=TRUE),"two distinct")
    expect_error(fastglm:::.ordinal_response_data(matrix(1,2,2),c(0,0),firth=TRUE),"positive total")
    expect_error(fastglm:::.ordinal_response_data(matrix(1,2,2),c(1,-1),firth=TRUE),"nonnegative")
})

test_that("expanded boundary covariance records the reduced rank", {
    a<-fastglm:::.ordinal_response_data(matrix(c(2,0,3,0,4),1),firth=TRUE)
    alpha<-c(-.8,.9);v<-matrix(c(.7,.2,.2,.6),2)
    expanded<-v[a$threshold.map,a$threshold.map,drop=FALSE]
    expect_identical(alpha[a$threshold.map],c(-.8,-.8,.9,.9))
    expect_equal(qr(expanded)$rank,2L)
    expect_equal(expanded[1,],expanded[2,])
    expect_equal(expanded[3,],expanded[4,])
    p<-diff(c(0,plogis(alpha[a$threshold.map]),1))
    expect_identical(p[a$collapsed.categories],c(0,0))
    expect_equal(sum(p),1)
})

test_that("public boundary fits preserve the declared scale and qualify uncertainty", {
    counts<-matrix(c(0,0,3,4,0,0),1,dimnames=list(NULL,letters[1:6]))
    x<-matrix(numeric(),1,0)
    expect_warning(f<-fastglm_ordinal(x,counts,offset=.25,firth=TRUE),"empty interior ordinal categories")
    expected<-c(.5,0,3,4,0,.5)/8
    expect_equal(unname(coef(f,component="threshold")),qlogis(cumsum(expected)[1:5])+.25,tolerance=1e-8)
    expect_equal(f$rank,3L)
    expect_equal(nobs(f),7)
    expect_equal(f$nobs.rows,1L)
    expect_equal(unname(predict(f)),matrix(expected,1),tolerance=1e-9)
    v<-vcov(f)
    expect_true(all(is.na(v[c(1,2,4,5),])))
    expect_true(is.finite(v[3,3]))
    pp<-predict(f,se.fit=TRUE)
    expect_true(all(is.na(pp$se.fit[,c(2,5)])))
    expect_true(all(is.finite(pp$se.fit[,c(1,3,4,6)])))
    cp<-predict(f,type="cumulative",se.fit=TRUE)
    expect_equal(unname(cp$se.fit[,1]),unname(cp$se.fit[,2]))
    expect_equal(unname(cp$se.fit[,4]),unname(cp$se.fit[,5]))
    expect_true(all(is.finite(cp$se.fit)))
    positive<-counts>0
    expect_equal(as.numeric(logLik(f)),sum(counts[positive]*log(predict(f)[positive])),tolerance=1e-9)
    expect_error(fastglm_ordinal(x,counts),"infinite thresholds for empty endpoint")

    # A model frame must not discard declared response levels before mapping.
    d<-data.frame(y=ordered(rep(c("c","d"),c(3,4)),levels=letters[1:6]),off=.25)
    expect_warning(g<-fastglm_ordinal(y~offset(off),data=d,firth=TRUE),"empty interior ordinal categories")
    expect_identical(g$levels,letters[1:6])
    expect_equal(unname(coef(g)),unname(coef(f)),tolerance=1e-8)
    expect_equal(unname(predict(g)),matrix(expected,7,6,byrow=TRUE),tolerance=1e-9)
})

test_that("dense count fits require named columns to match the declared levels", {
    set.seed(123)
    x <- cbind(a=rnorm(120))
    y <- ordered(sample(c("l","m","h"),120,TRUE),levels=c("l","m","h"))
    counts <- t(vapply(seq_along(y),function(i)as.numeric(levels(y)==y[i]),numeric(3)))
    colnames(counts) <- levels(y)
    ordered.fit <- fastglm_ordinal(x,counts,levels=levels(y))
    expect_equal(coef(ordered.fit),coef(fastglm_ordinal(x,y)),tolerance=1e-7)
    expect_error(fastglm_ordinal(x,counts[,c("h","m","l")],levels=levels(y)),"must match 'levels' in order")
    expect_error(fastglm_ordinal(x,`colnames<-`(counts,c("p","q","r")),levels=levels(y)),"must match 'levels' in order")
    expect_equal(coef(fastglm_ordinal(x,unname(counts),levels=levels(y))),coef(ordered.fit))
})
