test_that("diagnostics display readable checks and retain exact numerical fields", {
    set.seed(111304)
    x <- cbind("(Intercept)"=1,x=rnorm(80))
    y <- rgamma(80,shape=3,scale=exp(.2+.3*x[,2])/3)
    ordinary <- fastglm(x,y,Gamma("log"),method="auto")
    reduced <- fastglm(x,y,Gamma("log"),method="auto",firth=TRUE)
    ordinal <- fastglm_ordinal(x[,2,drop=FALSE],ordered(rep(1:4,20)),firth=TRUE)
    for(fit in list(ordinary,reduced,ordinal)) {
        d <- fastglm_diagnostics(fit)
        before <- serialize(d,NULL)
        printed <- capture.output(value <- print(d,digits=3))
        expect_s3_class(d,"fastglm_diagnostics")
        expect_identical(value,d)
        expect_true(any(grepl("Convergence: converged",printed,fixed=TRUE)))
        expect_false(any(grepl("^\\$|^\\[1\\]",printed)))
        tab <- as.data.frame(d)
        expect_identical(tab$converged,d$converged)
        expect_identical(tab$standardized.score,d$standardized.score)
        expect_identical(tab$score[[1]],d$score)
        expect_equal(nrow(tab),1)
        expect_identical(serialize(d,NULL),before)
    }
    expect_output(print(fastglm_diagnostics(ordinary)),"Cholesky \\(LLT\\)")
    expect_true(grepl("ordinary\\s+score need not be zero",
        paste(capture.output(print(fastglm_diagnostics(reduced))),collapse=" ")))
    compact <- fastglm(x,y,Gamma("log"),firth=TRUE,inference="none",retain.data=FALSE)
    expect_output(print(fastglm_diagnostics(compact)),"Unavailable")
    d <- fastglm_diagnostics(ordinary)
    d$converged <- FALSE; d$convergence.reason <- "iteration_limit"
    d$standardized.score <- 2.130616e-11
    expect_output(print(d,digits=4),"2.131e-11")
    expect_output(print(d),"not converged.*iteration limit")
    expect_identical(as.data.frame(d)$standardized.score,2.130616e-11)
    expect_error(print(d,digits=0),"digits")
})

test_that("prediction tables preserve row identities and matrix components", {
    set.seed(111305)
    d <- data.frame(x=rnorm(60),y=rpois(60,2),row.names=paste0("case",seq_len(60)))
    fit <- fastglm(y~x,d,poisson())
    pred <- predict(fit,d[c(5,2),],type="response",se.fit=TRUE)
    before <- serialize(pred,NULL)
    printed <- capture.output(value <- print(pred,digits=3,max.rows=1))
    tab <- as.data.frame(pred)
    expect_s3_class(pred,"fastglm_prediction")
    expect_identical(value,pred)
    expect_identical(tab$row,c("case5","case2"))
    expect_identical(tab$fit,unname(pred$fit))
    expect_identical(tab$se.fit,unname(pred$se.fit))
    expect_true(any(grepl("Estimate.*Std. Error",printed)))
    expect_true(any(grepl("1 of 2 rows",printed,fixed=TRUE)))
    expect_false(any(grepl("^\\$|^\\[1\\]",printed)))
    expect_identical(serialize(pred,NULL),before)
    expect_error(print(pred,max.rows=0),"max.rows")
    expect_error(print(pred,max.rows=NA_real_),"max.rows")

    ordinal <- fastglm_ordinal(ordered(1+y%%3)~x,d)
    pred <- predict(ordinal,d[c(5,2),],se.fit=TRUE)
    tab <- as.data.frame(pred)
    expect_identical(tab$row,rep(c("case5","case2"),each=3))
    expect_identical(tab$component,rep(colnames(pred$fit),times=2))
    for(i in seq_len(nrow(tab))) {
        expect_identical(tab$fit[i],unname(pred$fit[tab$row[i],tab$component[i]]))
        expect_identical(tab$se.fit[i],unname(pred$se.fit[tab$row[i],tab$component[i]]))
    }
    expect_output(print(pred,max.rows=4),"4 of 6 rows")
    expect_output(print(pred,max.rows=Inf),"case2")
    empty <- predict(ordinal,d[FALSE,],se.fit=TRUE)
    expect_equal(nrow(as.data.frame(empty)),0)
    expect_silent(capture.output(print(empty)))
    terms <- predict(fit,d[1:2,],type="terms",se.fit=TRUE)
    expect_identical(as.data.frame(terms)$component,rep("x",2))
    expect_identical(as.data.frame(terms)$fit,as.numeric(terms$fit))
})

test_that("all prediction interfaces share the display including streaming blocks", {
    set.seed(111306)
    d <- data.frame(x=runif(80,-1,1),y=rpois(80,2),positive=rgamma(80,2))
    models <- list(fastglm(y~x,d,family=negbin(2)),fastglm_hurdle(y~x,data=d),
        fastglm_zi(y~x,data=d),fastglm_truncated(y~x,data=d[d$y>0,]),
        fastglm_twopart(ifelse(y>0,positive,0)~x,data=d))
    for(model in models) {
        pred <- predict(model,newdata=d[1:2,],type="response",se.fit=TRUE)
        expect_s3_class(pred,"fastglm_prediction")
        expect_output(print(pred),"Estimate.*Std. Error")
        expect_identical(as.data.frame(pred)$fit,as.numeric(pred$fit))
        expect_identical(as.data.frame(pred)$se.fit,as.numeric(pred$se.fit))
    }
    reader <- function(k) d[((k-1)*40+1):(k*40),]
    source <- fastglm_source(reader,2,formula=y~x,prototype=d)
    stream <- fastglm_streaming(source,family=poisson())
    pred <- predict(stream,type="response",se.fit=TRUE)
    pieces <- list()
    predict(stream,type="response",se.fit=TRUE,sink=function(value,k) pieces[[k]] <<- value)
    expect_true(all(vapply(pieces,inherits,logical(1),"fastglm_prediction")))
    expect_equal(pred$fit,unlist(lapply(pieces,`[[`,"fit"),use.names=FALSE))
    expect_equal(pred$se.fit,unlist(lapply(pieces,`[[`,"se.fit"),use.names=FALSE))
    expect_output(print(pred,max.rows=2),"2 of 80 rows")
    source <- fastglm_source(reader,2,formula=y~x|x,prototype=d)
    stream <- fastglm_hurdle(source)
    pred <- predict(stream,type="prob",at=0:2,se.fit=TRUE)
    expect_s3_class(pred,"fastglm_prediction")
    expect_equal(nrow(as.data.frame(pred)),240)
    expect_equal(as.data.frame(pred)$fit,as.numeric(t(pred$fit)))
})

test_that("unavailable category uncertainty remains explicit in prediction output", {
    counts <- matrix(c(4,0,7,3),nrow=1,
        dimnames=list(NULL,c("low","mild","moderate","high")))
    expect_warning(fit <- fastglm_ordinal(matrix(numeric(),1,0),counts,firth=TRUE),"collapsed")
    pred <- predict(fit,se.fit=TRUE)
    tab <- as.data.frame(pred)
    expect_identical(tab$fit[tab$component=="mild"],0)
    expect_true(is.na(tab$se.fit[tab$component=="mild"]))
    expect_output(print(pred),"mild.*0.*NA")
    expect_output(print(pred),"reduced category model")
})
