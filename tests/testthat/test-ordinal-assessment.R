test_that("ordinal assessment scores individual outcomes within frequency rows", {
    x <- matrix(c(-1,0,1),ncol=1,dimnames=list(NULL,"x"))
    counts <- rbind(c(4,2,0),c(1,3,2),c(0,2,4))
    colnames(counts) <- c("low","middle","high")
    fit <- fastglm_ordinal(x,counts,firth=TRUE)
    weights <- c(.5,2,1)
    a <- fastglm_ordinal_assess(fit,newdata=x,y=counts,weights=weights,bins=4,
                              proportional.odds=TRUE)
    effective <- counts*weights
    row <- rep(seq_len(nrow(x)),rowSums(effective))
    code <- unlist(lapply(seq_len(nrow(x)),function(i) rep(1:3,effective[i,])))
    b <- fastglm_ordinal_assess(fit,newdata=x[row,,drop=FALSE],y=code,bins=4,
                              proportional.odds=TRUE)
    expect_equal(a$scores,b$scores,tolerance=1e-12)
    expect_equal(a$calibration,b$calibration,tolerance=1e-12)
    expect_equal(a$proportional.odds$estimate,b$proportional.odds$estimate,tolerance=1e-8)
    expect_equal(a$proportional.odds$std.error,b$proportional.odds$std.error,tolerance=1e-8)
    P <- predict(fit); F <- cbind(P[,1],P[,1]+P[,2])
    observed <- cbind(counts[,1],counts[,1]+counts[,2])/rowSums(counts)
    correct <- rowSums(F^2-2*F*observed+observed)
    expect_equal(a$rows$rps,unname(correct),tolerance=1e-12)
    expect_true(all(a$rows$rps>rowSums((F-observed)^2)))
    expect_equal(a$rows$log_loss,-rowSums(counts*log(P))/rowSums(counts),ignore_attr=TRUE)
    expect_equal(a$scores$rps_normalized,a$scores$rps/2)
    expect_identical(a$levels,colnames(counts))
    expect_identical(a$evaluation,"supplied outcomes")
    expect_named(a$exclusions,c("reason","rows"))
    shuffled <- fastglm_ordinal_assess(fit,newdata=x,y=counts[,c(3,1,2)],weights=weights,bins=4)
    expect_equal(shuffled$scores,a$scores)
    expect_equal(shuffled$calibration,a$calibration)
})

test_that("assessment outcomes cannot leak into prediction or calibration bins", {
    set.seed(110401)
    d <- data.frame(x=rnorm(120),off=rnorm(120,sd=.2))
    d$y <- ordered(findInterval(.7*d$x+d$off+rlogis(120),c(-.6,.8))+1,levels=1:3)
    fit <- fastglm_ordinal(y~x+offset(off),d,weights=rep(2,120),firth=TRUE)
    a <- fastglm_ordinal_assess(fit,newdata=d,y=d$y,bins=7)
    b <- fastglm_ordinal_assess(fit,newdata=d,y=ordered(4-as.integer(d$y),levels=1:3),bins=7)
    expect_equal(a$scores$frequency,120)
    expect_equal(fastglm_ordinal_assess(fit)$scores$frequency,240)
    expect_equal(a$calibration[,c("threshold","bin","frequency","predicted")],
                 b$calibration[,c("threshold","bin","frequency","predicted")])
    expect_false(isTRUE(all.equal(a$scores$log_loss,b$scores$log_loss)))
    matrix.a <- fastglm_ordinal_assess(fit,newdata=transform(d,off=0),y=d$y,offset=d$off,bins=7)
    expect_equal(a$scores,matrix.a$scores)
    expect_error(fastglm_ordinal_assess(fit,newdata=d),"supply assessment outcomes")
    expect_error(fastglm_ordinal_assess(fit,newdata=d,y=rep("unknown",120)),"unknown")
    expect_error(fastglm_ordinal_assess(fit,y=d$y,weights=rep(.5,120)),"integer")
    expect_error(fastglm_ordinal_assess(fit,bins=2.5),"positive integer")
    expect_error(fastglm_ordinal_assess(fit,proportional.odds=NA),"TRUE or FALSE")
})

test_that("ordinal assessment retains excluded and missing rows", {
    d <- data.frame(x=seq(-2,2,length.out=90),y=ordered(rep(1:3,30)))
    d$x[2] <- NA; d$y[4] <- NA
    fit <- fastglm_ordinal(y~x,d,na.action=na.exclude,firth=TRUE)
    a <- fastglm_ordinal_assess(fit)
    expect_equal(nrow(a$rows),90)
    expect_equal(a$rows$exclusion[c(2,4)],rep("omitted_during_fitting",2))
    expect_false(any(a$rows$included[c(2,4)]))
    expect_true(all(is.na(a$rows$log_loss[c(2,4)])))
    expect_equal(a$scores$frequency,88)
    new <- data.frame(x=c(NA,0,1,2,3,4))
    b <- fastglm_ordinal_assess(fit,newdata=new,y=c(1,NA,2,3,2,1),weights=c(1,1,0,NA,2,1))
    expect_equal(b$rows$exclusion,c("missing_predictor_or_offset","missing_outcome",
                                   "zero_frequency","missing_weight","",""))
    expect_equal(b$scores$frequency,3)
    expect_true(all(is.na(b$rows$rps[1:4])))
    expect_equal(sum(b$exclusions$rows),4)
    zero <- fastglm_ordinal_assess(fit,newdata=new[2:3,,drop=FALSE],y=c(1,2),weights=c(0,0))
    expect_equal(zero$scores$frequency,0)
    expect_true(all(is.na(zero$scores[,-1])))
    expect_true(all(zero$calibration$frequency==0))
    expect_true(all(is.na(zero$calibration$predicted)))
    empty <- fastglm_ordinal_assess(fit,newdata=new[FALSE,,drop=FALSE],y=integer())
    expect_equal(nrow(empty$rows),0)
    expect_equal(empty$scores$frequency,0)
    expect_error(fastglm_ordinal_assess(fit,newdata=data.frame(x=Inf),y=1),"finite or missing")
})

test_that("structural zeros and tiny ordinal tails have honest log scores", {
    x <- matrix(numeric(),1,0)
    expect_warning(fit <- fastglm_ordinal(x,matrix(c(4,0,5),1),firth=TRUE),"empty interior")
    a <- fastglm_ordinal_assess(fit)
    expect_true(is.finite(a$scores$log_loss))
    b <- fastglm_ordinal_assess(fit,newdata=x,y=2)
    expect_identical(b$scores$log_loss,Inf)
    expect_true(is.finite(b$scores$rps))
    expect_equal(b$calibration$predicted[1:10],b$calibration$predicted[11:20])
    full <- fastglm_ordinal(x,matrix(c(2,3,4),1),firth=TRUE)
    extreme <- fastglm_ordinal_assess(full,newdata=x,y=1,offset=1000)
    expect_equal(extreme$scores$log_loss,1000-full$alpha[1],ignore_attr=TRUE)
    expect_equal(extreme$scores$rps_normalized,1)
    expect_equal(unname(predict(full,newdata=x,offset=1000)[1,1]),0)
    middle <- fastglm_ordinal_assess(full,newdata=x,y=2,offset=740)
    expected <- -plogis(full$alpha[2]-740,log.p=TRUE)-
        log(-expm1(full$alpha[1]-full$alpha[2]))-plogis(740-full$alpha[1],log.p=TRUE)
    expect_equal(middle$scores$log_loss,unname(expected))
    # No cancellation of a rare upper outcome beside a huge lower count.
    huge <- fastglm_ordinal_assess(full,newdata=x,y=matrix(c(1e16,1,1),1))
    P <- predict(full)
    expected.rps <- sum(c(1,1)*c(1-P[1,1],P[1,3])^2+
        c(2e-16,1e-16)*c(P[1,1],1-P[1,3])^2)
    expect_equal(huge$scores$rps,expected.rps,tolerance=1e-14)
})

test_that("proportional-odds comparisons use supplied data and retain failures", {
    x <- matrix(seq(-2,2,length.out=120),ncol=1,dimnames=list(NULL,"x"))
    y <- ordered(rep(1:3,40))
    fit <- fastglm_ordinal(x,y,firth=TRUE)
    held <- ordered(findInterval(x[,1],c(-.5,.6))+1,levels=1:3)
    a <- fastglm_ordinal_assess(fit,newdata=x,y=held,proportional.odds=TRUE)
    expect_true(all(a$proportional.odds$converged))
    expect_true(all(a$proportional.odds$estimate>1))
    expect_true(all(nzchar(a$proportional.odds$warning)))
    expect_equal(a$proportional.odds$common.estimate,rep(unname(fit$beta),2))
    for(j in 1:2) {
        expect_warning(binary <- fastglm(cbind(1,x),as.numeric(as.integer(held)>j),
            family=binomial(),firth=TRUE,method="auto",maxit=200),"numerically 0 or 1")
        expect_equal(a$proportional.odds$estimate[j],unname(coef(binary)[2]),tolerance=1e-10)
        expect_equal(a$proportional.odds$std.error[j],sqrt(vcov(binary)[2,2]),tolerance=1e-10)
    }
    failed <- fastglm_ordinal_assess(fit,newdata=x,y=held,proportional.odds=TRUE,po.control=list(maxit=1))
    expect_false(any(failed$proportional.odds$converged))
    expect_true(all(is.na(failed$proportional.odds$estimate)))
    expect_equal(nrow(failed$proportional.odds),2)
    none <- fastglm_ordinal_assess(fit,newdata=x,y=rep(1,120),proportional.odds=TRUE)
    expect_equal(none$proportional.odds$reason,rep("no_outcome_variation",2))
    expect_equal(none$proportional.odds$event.frequency,c(0,0))
    extreme.counts <- matrix(rep(c(1,0,1e16),3),3,3,byrow=TRUE)
    tails <- fastglm_ordinal_assess(fit,newdata=matrix(c(-1,0,1),ncol=1),
        y=extreme.counts,proportional.odds=TRUE)
    expect_equal(tails$proportional.odds$reason,rep("unrepresentable_binary_counts",2))
    expect_equal(tails$proportional.odds$nonevent.frequency,c(3,3))
    expect_true(all(is.finite(unlist(tails$scores))))
    rank.lost <- fastglm_ordinal_assess(fit,newdata=matrix(0,120,1),y=held,proportional.odds=TRUE)
    expect_false(any(rank.lost$proportional.odds$converged))
    expect_true(all(is.na(rank.lost$proportional.odds$estimate)))
    expect_error(fastglm_ordinal_assess(fit,proportional.odds=TRUE,po.control=list(toll=1e-6)),"permits only")
    path <- tempfile(fileext=".pdf")
    grDevices::pdf(path); on.exit({ grDevices::dev.off(); unlink(path) },add=TRUE)
    expect_silent(plot(a))
    expect_silent(plot(a,type="proportional.odds"))
    expect_silent(plot(none,type="proportional.odds"))
    expect_silent(plot(a,main="Calibration",xlab="Predicted",ylab="Observed",pch=1))
    expect_silent(plot(a,type="proportional.odds",main="Slopes",xlab="Threshold",ylab="Estimate",pch=1))
    expect_invisible(plot(a))
    # Both displays draw without ggplot2, which is only suggested.
    expect_silent(fastglm:::.ordinal_assessment_base_plot(a,"calibration",seq_len(length(a$levels)-1L),0.95,list()))
    expect_silent(fastglm:::.ordinal_assessment_base_plot(a,"proportional.odds",unique(a$proportional.odds$term),0.95,list(main="Slopes")))
    skip_if_not_installed("ggplot2")
    drawn <- fastglm:::.ordinal_assessment_ggplot(a,"calibration",seq_len(length(a$levels)-1L),0.95,list(main="Calibration",xlab="Predicted"))
    expect_s3_class(drawn,"ggplot")
    expect_identical(drawn$labels$title,"Calibration")
    expect_identical(drawn$labels$x,"Predicted")
    expect_s3_class(fastglm:::.ordinal_assessment_ggplot(a,"proportional.odds",unique(a$proportional.odds$term),0.95,list()),"ggplot")
    expect_output(print(a),"Ordinal assessment")
})

test_that("blocked and sparse assessment preserve category order and probabilities", {
    skip_if_not_installed("Matrix")
    set.seed(110402)
    x <- matrix(rnorm(200*2),200,2,dimnames=list(NULL,c("a","b")))
    y <- ordered(rep(c("low","middle","high","top"),50),levels=c("low","middle","high","top"))
    fit <- fastglm_ordinal(x,y,firth=TRUE)
    a <- fastglm_ordinal_assess(fit,proportional.odds=TRUE)
    fit$block.size <- 7L
    b <- fastglm_ordinal_assess(fit,newdata=Matrix::Matrix(x[,2:1],sparse=TRUE),
        y=factor(as.character(y),levels=rev(levels(y))),proportional.odds=TRUE)
    expect_equal(a$scores,b$scores,tolerance=1e-12)
    expect_equal(a$calibration,b$calibration,tolerance=1e-12)
    expect_equal(a$proportional.odds$estimate,b$proportional.odds$estimate,tolerance=1e-7)
    expect_equal(a$levels,b$levels)
    binary <- fastglm_ordinal(matrix(numeric(),200,0),ordered(as.integer(y)>2),firth=TRUE)
    binary.a <- fastglm_ordinal_assess(binary,proportional.odds=TRUE)
    expect_equal(binary.a$scores$rps,binary.a$scores$rps_normalized)
    expect_equal(nrow(binary.a$proportional.odds),0)
})
